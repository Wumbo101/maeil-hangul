const byId = new Map(JAMO.map((jamo) => [jamo.id, jamo]))
const byChar = new Map(JAMO.map((jamo) => [jamo.char, jamo]))

export function jamoById(id: string): Jamo {
  const jamo = byId.get(id)
  if (!jamo) throw new Error(`Unknown jamo id: ${id}`)
  return jamo
}

export function jamoByChar(char: string): Jamo | undefined {
  return byChar.get(char)
}
